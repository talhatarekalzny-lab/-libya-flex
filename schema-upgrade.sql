-- Extend the checkout RPC with server-side coupon validation and usage counting.
create or replace function public.create_store_order(payload jsonb)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order_id bigint;
  v_item jsonb;
  v_product public.products%rowtype;
  v_variant public.product_variants%rowtype;
  v_coupon public.store_coupons%rowtype;
  v_qty integer;
  v_product_id bigint;
  v_variant_id bigint;
  v_subtotal numeric(10,2) := 0;
  v_total numeric(10,2) := 0;
  v_fee numeric(10,2) := 0;
  v_discount numeric(10,2) := 0;
  v_unit numeric(10,2);
  v_size text;
  v_color text;
  v_name text;
  v_phone text;
  v_city text;
  v_address text;
  v_email text;
  v_coupon_code text;
  v_settings public.store_settings%rowtype;
begin
  if jsonb_typeof(payload) <> 'object' then raise exception 'Invalid order payload'; end if;
  v_name := nullif(trim(payload->>'customer_name'), '');
  v_phone := nullif(trim(payload->>'customer_phone'), '');
  v_city := nullif(trim(payload->>'city'), '');
  v_address := nullif(trim(payload->>'delivery_address'), '');
  v_email := nullif(trim(payload->>'customer_email'), '');
  if v_name is null or v_phone is null or v_city is null or v_address is null then raise exception 'أكمل بيانات التوصيل'; end if;
  if jsonb_typeof(payload->'items') <> 'array' or jsonb_array_length(payload->'items') < 1 then raise exception 'السلة فارغة'; end if;
  if jsonb_array_length(payload->'items') > 30 then raise exception 'عدد المنتجات كبير جداً'; end if;
  select * into v_settings from public.store_settings where id = 1;
  if not found or not v_settings.is_store_open then raise exception 'المتجر مغلق حالياً'; end if;
  v_fee := greatest(coalesce(v_settings.delivery_fee, 0), 0);

  for v_item in select value from jsonb_array_elements(payload->'items') loop
    v_product_id := (v_item->>'product_id')::bigint;
    v_qty := (v_item->>'quantity')::integer;
    v_variant_id := nullif(v_item->>'variant_id','')::bigint;
    if v_qty is null or v_qty < 1 or v_qty > 20 then raise exception 'كمية غير صالحة'; end if;
    select * into v_product from public.products where id = v_product_id and is_active = true for update;
    if not found then raise exception 'أحد المنتجات لم يعد متاحاً'; end if;
    if v_variant_id is null and exists(select 1 from public.product_variants where product_id = v_product_id) then raise exception 'اختار المقاس أولاً'; end if;
    if v_variant_id is null and v_product.stock_quantity < v_qty then raise exception 'الكمية غير متوفرة: %', v_product.name; end if;
    v_unit := v_product.price;
    if v_variant_id is not null then
      select * into v_variant from public.product_variants where id = v_variant_id and product_id = v_product_id for update;
      if not found then raise exception 'المقاس غير متاح'; end if;
      if v_variant.stock_quantity < v_qty then raise exception 'الكمية غير متوفرة للمقاس المختار'; end if;
      v_unit := coalesce(v_variant.price, v_product.price);
    end if;
    v_subtotal := v_subtotal + (v_unit * v_qty);
  end loop;

  v_coupon_code := upper(nullif(trim(payload->>'coupon_code'), ''));
  if v_coupon_code is not null then
    select * into v_coupon from public.store_coupons where upper(code) = v_coupon_code and is_active = true for update;
    if not found or (v_coupon.starts_at is not null and now() < v_coupon.starts_at)
      or (v_coupon.ends_at is not null and now() > v_coupon.ends_at)
      or (v_coupon.usage_limit is not null and v_coupon.used_count >= v_coupon.usage_limit)
      or v_subtotal < v_coupon.min_order then raise exception 'كود الخصم غير صالح أو غير مستوفٍ للشروط'; end if;
    if v_coupon.discount_type = 'percent' then v_discount := round(v_subtotal * least(v_coupon.discount_value,100) / 100, 2);
    else v_discount := least(v_coupon.discount_value, v_subtotal); end if;
    update public.store_coupons set used_count = used_count + 1 where id = v_coupon.id;
  end if;
  v_total := greatest(v_subtotal - v_discount, 0) + v_fee;

  insert into public.orders(customer_name, customer_phone, customer_email, delivery_address, city, total_amount, status, notes)
  values(v_name, v_phone, v_email, v_address, v_city, v_total, 'pending',
    concat_ws(' | ', case when v_fee > 0 then 'رسوم التوصيل: ' || v_fee::text end,
      case when v_discount > 0 then 'خصم: ' || v_discount::text || ' ( ' || v_coupon_code || ' )' end))
  returning id into v_order_id;

  for v_item in select value from jsonb_array_elements(payload->'items') loop
    v_product_id := (v_item->>'product_id')::bigint;
    v_qty := (v_item->>'quantity')::integer;
    v_variant_id := nullif(v_item->>'variant_id','')::bigint;
    select * into v_product from public.products where id = v_product_id and is_active = true for update;
    v_unit := v_product.price; v_size := nullif(v_item->>'size',''); v_color := nullif(v_item->>'color','');
    if v_variant_id is not null then
      select * into v_variant from public.product_variants where id = v_variant_id and product_id = v_product_id for update;
      v_unit := coalesce(v_variant.price, v_product.price);
      update public.product_variants set stock_quantity = stock_quantity - v_qty where id = v_variant_id;
      v_size := coalesce(v_size, v_variant.size); v_color := coalesce(v_color, v_variant.color);
    else
      update public.products set stock_quantity = stock_quantity - v_qty, updated_at = now() where id = v_product_id;
    end if;
    insert into public.order_items(order_id, product_id, variant_id, product_name, size, color, quantity, unit_price)
    values(v_order_id, v_product_id, v_variant_id, v_product.name, v_size, v_color, v_qty, v_unit);
  end loop;
  insert into public.delivery_history(order_id, status, notes) values(v_order_id, 'pending', 'طلب جديد من المتجر');
  return v_order_id;
end;
$$;
revoke all on function public.create_store_order(jsonb) from public;
grant execute on function public.create_store_order(jsonb) to anon, authenticated;

